#!/usr/bin/env python3
"""Calibrate the character-consistency threshold on labelled mock data.

Why this exists: the brief asks us to defend every number. `0.75` should not be a
vibe — this script produces the precision/recall table and the cost curve behind it.

Ground truth: the mock image provider decides drift deterministically from
(prompt, seed), so we can label each synthetic shot exactly. The mock's
embeddings are bimodal by construction (related vs unrelated to the character
reference), which makes the *method* demonstrable but means the absolute scores
must be recalibrated on real provider embeddings before production.

Usage:
    .venv/bin/python tools/calibrate.py --samples 4000
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from mocks.main import DRIFT_RATE, _cosine, _embedding, _vector  # noqa: E402

REFERENCE = "Maya, 28, marine biologist, curly black hair, yellow raincoat"
PROMPTS = [
    "Maya steers a small boat through rough water",
    "close-up of Maya laughing in the rain",
    "Maya points at a pod of dolphins",
    "wide shot of Maya on the harbour at dawn",
    "Maya repairs a net on the deck",
    "Maya looks at a storm on the horizon",
]
REGEN_COST_CENTS = 100     # one extra image generation (see price_table)
MISS_COST_CENTS = 1000     # a bad shot slips into the final film


def build_samples(n: int, seed: int = 7) -> list[tuple[float, bool]]:
    rng = random.Random(seed)
    reference = _vector(REFERENCE, "reference")
    rows: list[tuple[float, bool]] = []
    for i in range(n):
        prompt = f"{rng.choice(PROMPTS)} [{i}]"
        shot_seed = rng.randrange(1, 10**9)
        embedding = _embedding(prompt, shot_seed, REFERENCE)
        score = _cosine(reference, embedding)
        drifted = random.Random(f"{prompt}|{shot_seed}").random() < DRIFT_RATE
        rows.append((score, drifted))
    return rows


def sweep(rows, thresholds):
    table = []
    for t in thresholds:
        tp = fp = tn = fn = 0
        for score, drifted in rows:
            flagged = score < t
            if drifted and flagged:
                tp += 1
            elif drifted and not flagged:
                fn += 1
            elif not drifted and flagged:
                fp += 1
            else:
                tn += 1
        precision = tp / (tp + fp) if tp + fp else 1.0
        recall = tp / (tp + fn) if tp + fn else 1.0
        cost = (fp * REGEN_COST_CENTS + fn * MISS_COST_CENTS) / len(rows)
        table.append(
            {
                "threshold": t,
                "tp": tp, "fp": fp, "tn": tn, "fn": fn,
                "precision": precision,
                "recall": recall,
                "cost_cents_per_shot": cost,
            }
        )
    return table


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", type=int, default=4000)
    ap.add_argument("--out", default=str(ROOT / "docs" / "calibration.md"))
    args = ap.parse_args()

    rows = build_samples(args.samples)
    good = [s for s, drifted in rows if not drifted]
    bad = [s for s, drifted in rows if drifted]
    good.sort()
    bad.sort()

    fine = [i / 100 for i in range(50, 99)]
    table = sweep(rows, fine)
    best_cost = min(r["cost_cents_per_shot"] for r in table)
    zero_cost = [r for r in table if r["cost_cents_per_shot"] == best_cost]
    band_lo, band_hi = zero_cost[0]["threshold"], zero_cost[-1]["threshold"]
    midpoint = (band_lo + band_hi) / 2
    best = min(zero_cost, key=lambda r: abs(r["threshold"] - midpoint))

    coarse = [t for t in (0.50, 0.60, 0.70, 0.75, 0.80, 0.85, 0.90, 0.95)]
    coarse_rows = sweep(rows, coarse)

    lines: list[str] = []
    lines.append("# Consistency threshold calibration\n")
    lines.append(
        f"Generated by `tools/calibrate.py` on {len(rows)} synthetic shots "
        f"({len(bad)} drifted, {len(good)} consistent) using the mock provider's "
        f"deterministic drift model (`DRIFT_RATE={DRIFT_RATE}`).\n"
    )
    lines.append(
        "Cost model: a false positive pays for one unnecessary regeneration "
        f"({REGEN_COST_CENTS}¢); a false negative ships a bad shot "
        f"({MISS_COST_CENTS}¢).\n"
    )
    lines.append("## Score distribution\n")
    lines.append("| class | min | p50 | max |\n|---|---|---|---|")
    lines.append(
        f"| consistent | {good[0]:.3f} | {good[len(good)//2]:.3f} | {good[-1]:.3f} |"
    )
    lines.append(
        f"| drifted | {bad[0]:.3f} | {bad[len(bad)//2]:.3f} | {bad[-1]:.3f} |"
    )
    margin = good[0] - bad[-1]
    lines.append(
        f"\nGap between the worst consistent score and the best drifted score: "
        f"**{margin:.3f}**. Any threshold inside that gap separates the classes "
        f"perfectly on this dataset.\n"
    )
    lines.append("## Coarse sweep\n")
    lines.append("| threshold | precision | recall | cost (¢/shot) |\n|---|---|---|---|")
    for r in coarse_rows:
        lines.append(
            f"| {r['threshold']:.2f} | {r['precision']:.3f} | {r['recall']:.3f} "
            f"| {r['cost_cents_per_shot']:.2f} |"
        )
    lines.append(
        f"\nZero-cost band on the fine sweep: **{band_lo:.2f} – {band_hi:.2f}**, "
        f"midpoint **{best['threshold']:.2f}** "
        f"(precision {best['precision']:.3f}, recall {best['recall']:.3f}, "
        f"cost {best['cost_cents_per_shot']:.2f}¢/shot).\n"
    )
    lines.append(
        f"The pipeline default is `CONSISTENCY_THRESHOLD=0.75`: the sweep independently "
        f"lands at {best['threshold']:.2f}, and 0.75 sits inside the empirical gap "
        f"({bad[-1]:.3f} … {good[0]:.3f}).\n"
    )
    lines.append("## Honest limitations\n")
    lines.append(
        "- The mock embedding space is bimodal: real image embeddings are continuous, "
        "so precision/recall will drop and this threshold must be recalibrated on "
        "labelled real generations.\n"
        "- Both costs in the model are placeholders from the demo price table; the "
        "method (sweep + expected cost) is what transfers, not the exact 0.75.\n"
        "- Regeneration is accepted after at most 2 attempts; the miss rate after "
        "two attempts is `DRIFT_RATE²` = "
        f"{DRIFT_RATE ** 2:.2%} under this independent-drift model."
    )

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")

    print("\n".join(lines))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
